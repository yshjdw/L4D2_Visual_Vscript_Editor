def insert_named_helpers(source):
    required = set(re.findall(r'::L4VP_Utils\.([A-Za-z_]+)\s*\(', source))
    unknown = required - FUNCTIONS.keys()
    if unknown:
        raise ValueError('Unknown L4VP helper(s): ' + ', '.join(sorted(unknown)))
    def add_dependencies(name):
        for dep in FUNCTIONS[name][0]:
            if dep not in required:
                required.add(dep)
                add_dependencies(dep)
    for name in tuple(required):
        add_dependencies(name)
    if not required:
        return source
    definitions = ['::L4VP_Utils <- {};']
    for name in FUNCTIONS:
        if name not in required:
            continue
        _, code, params = FUNCTIONS[name]
        definitions.append('::L4VP_Utils.' + name + ' <- function(' + params + ')')
        definitions.append('{')
        definitions.extend('    ' + line if line else '' for line in code.splitlines())
        definitions.append('};')
    definitions.append('')
    lines = source.splitlines(keepends=True)
    pos = 2 if len(lines) >= 2 and lines[0].startswith('// Generated by') else 0
    return ''.join(lines[:pos]) + '\n' + '\n'.join(definitions) + ''.join(lines[pos:])
